def fx_textures():
    """(name, image) for every res://p5joker/fx/<name>.png; also used by tools/p5/fxpreview/prepare.py."""
    for name, src in FX_TEX.items():
        yield name, Image.open(FX / src).convert("RGBA")
    for name, idx in BTN_TEX.items():
        im = Image.open(BTN / f"{idx:05d}.png").convert("RGBA")
        pad = Image.new("RGBA", (im.width + 32, im.height + 32), (0, 0, 0, 0))
        pad.alpha_composite(im, (16, 16))
        yield name, pad
    for name, (idx, k) in DMG_TEX.items():
        im = Image.open(DMG / f"{idx:05d}.png").convert("RGBA")
        yield name, im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
    for name in GEN_TEX:
        drawn = GEN_CODEX / f"{name}.png"                 # Codex's drawn version wins over the scripted one (user 2026-10-28)
        yield name, Image.open(drawn if drawn.exists() else GEN / f"{name}.png").convert("RGBA")
    # shiv ammo cylinder UI (Codex): optional until drawn
    for name in ("ammo_cylinder", "ammo_round", "ammo_spent"):
        if (GEN_CODEX / f"{name}.png").exists():
            yield name, Image.open(GEN_CODEX / f"{name}.png").convert("RGBA")
    # calling card back: Codex draws calling_card_back.png; until then a placeholder (black card, red border + stripes, card's
    # own silhouette) so CardFx.Neutralize can flip front/back
    back = GEN_CODEX / "calling_card_back.png"
    yield "calling_card_back", Image.open(back).convert("RGBA") if back.exists() else placeholder_back()
    # Codex delivered the band squashed from 1983x793 to 1600x420 (README_codex.md); undo the squash until the raw
    # image is in the repo (art/p5/fx/gen_codex/cutin_band_raw.png wins when present)
    raw = GEN_CODEX / "cutin_band_raw.png"
    band = Image.open(raw if raw.exists() else GEN_CODEX / "cutin_band.png").convert("RGBA")
    if not raw.exists():
        band = band.resize((1983, 793), Image.LANCZOS)
    yield "cutin_band", band
    eyes = Image.open(EYES).convert("RGBA")
    yield "eyes", eyes.resize((eyes.width // 2, eyes.height // 2), Image.LANCZOS)
    yield "arsene_cast", arsene_atlas()
    # Izanagi-no-Okami (Codex render of BPS0360_000_main_0006, art/p5/fx/izanagi_okami): spin action atlas + weapon alone
    if (IZANAGI / "spin").exists():
        yield "izanagi_spin", izanagi_atlas()
        w = Image.open(IZANAGI / "weapon.png").convert("RGBA")
        yield "izanagi_weapon", w.resize((w.width // 2, w.height // 2), Image.LANCZOS)
    # eye cut-in band tails (Codex, art/p5/fx/gen_codex/cutin_tails): only the left one was drawn - the right one is the left
    # rotated 180 deg (band entering from the left edge, rising to the right). Kept at full size (they are scaled in CutIn.cs)
    tail = GEN_CODEX / "cutin_tails" / "cutin_tail_left.png"
    right = GEN_CODEX / "cutin_tails" / "cutin_tail_right.png"
    if tail.exists():
        im = Image.open(tail).convert("RGBA")
        yield "cutin_tail_left", im
        yield "cutin_tail_right", Image.open(right).convert("RGBA") if right.exists() else im.rotate(180)
    # hit / guard ink art (Codex, art/p5/fx/gen_codex/ink): brush slashes, ink splatters, guard glass barrier. Optional:
    # p5mod/src/Vfx/Ink.cs uses each one only if it is in the pck. Long side capped at 1024.
    for src in sorted((GEN_CODEX / "ink").glob("*.png")) if (GEN_CODEX / "ink").exists() else []:
        if src.stem.startswith(("ink_slash_", "ink_splat_", "guard_")):
            im = Image.open(src).convert("RGBA")
            a = im.getchannel("A").point(lambda v: 0 if v < 20 else v)     # Codex can't clean stray specks (no python there)
            im.putalpha(a)
            k = min(1.0, 1024 / max(im.size))
            yield src.stem, im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS) if k < 1 else im
    # curse hands for Eiha (Codex, art/p5/fx/gen_codex/curse_hands, 1024x1536) at half size
    for name in ("hand_reach", "hand_slam", "hand_claw", "hand_grab"):
        src = GEN_CODEX / "curse_hands" / f"{name}.png"
        if src.exists():
            im = Image.open(src).convert("RGBA")
            yield name, im.resize((im.width // 2, im.height // 2), Image.LANCZOS)


# Arsene's cast action rendered from the original P5R model (art/p5/fx/arsene/cast, 49 frames of 1490x1024,
# sources.json): packed 7 per row at ARSENE_K of the size for the summon (p5mod/src/Vfx/Persona.cs)
ARSENE = ROOT / "art/p5/fx/arsene"
ARSENE_K, ARSENE_COLS = 0.45, 7


IZANAGI = ROOT / "art/p5/fx/izanagi_okami"
IZANAGI_K, IZANAGI_COLS = 0.45, 7


def izanagi_atlas():
    """all 51 spin frames (824x1024) at IZANAGI_K, 7 per row (p5mod/src/Vfx/Persona.cs Izanagi spec)."""
    frames = sorted((IZANAGI / "spin").glob("[0-9]*.png"))
    w, h = round(824 * IZANAGI_K), round(1024 * IZANAGI_K)
    rows = (len(frames) + IZANAGI_COLS - 1) // IZANAGI_COLS
    atlas = Image.new("RGBA", (w * IZANAGI_COLS, h * rows), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        atlas.paste(Image.open(f).convert("RGBA").resize((w, h), Image.LANCZOS), (i % IZANAGI_COLS * w, i // IZANAGI_COLS * h))
    return atlas


def arsene_atlas():
    frames = sorted((ARSENE / "cast").glob("*.png"))
    w, h = round(1490 * ARSENE_K), round(1024 * ARSENE_K)
    rows = (len(frames) + ARSENE_COLS - 1) // ARSENE_COLS
    atlas = Image.new("RGBA", (w * ARSENE_COLS, h * rows), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        im = Image.open(f).convert("RGBA").resize((w, h), Image.LANCZOS)
        atlas.paste(im, (i % ARSENE_COLS * w, i // ARSENE_COLS * h))
    return atlas


def main():
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        renamed("joker", "silent", tmp)
        stage_spine(STAGE, "animations/characters/silent", "silent", tmp, "silent_skel_data",
                    atlas_uid="dq7y3dlq1mmdq", png_uid="bvmfj1e5yasw2", skel_data_uid="bqlhf04mk2866", default_mix=0.05,
                    mixes=[("idle_loop", "hurt", 0.02), ("hurt", "die", 0.1), ("cast", "idle_loop", 0.08)])
        shutil.copy(RIG / "restsite_silent.spine-json", tmp / "restsite_silent.spine-json")
        shutil.copy(RIG / "restsite_silent.png", tmp / "restsite_silent.png")
        shutil.copy(RIG / "restsite_silent.atlas", tmp / "restsite_silent.atlas")
        stage_spine(STAGE, "animations/rest_site/silent", "restsite_silent", tmp, "rest_site_silent_skel_data",
                    atlas_uid="chhushd3ctbab", png_uid="b6n6lfy1rklgq", skel_data_uid="cusnivp587wn0", default_mix=0.2)
    shop = STAGE / "animations/merchant/silent"
    shop.mkdir(parents=True)
    (shop / "silent_merchant_skel_data.tres").write_text("""[gd_resource type="SpineSkeletonDataResource" load_steps=3 format=3 uid="uid://d4li4q7d3n0nb"]

[ext_resource type="SpineAtlasResource" path="res://animations/characters/silent/silent.atlas" id="1_atlas"]
[ext_resource type="SpineSkeletonFileResource" path="res://animations/characters/silent/silent.spine-json" id="2_skel"]

[resource]
atlas_res = ExtResource("1_atlas")
skeleton_file_res = ExtResource("2_skel")
default_mix = 0.1
""")
    for name, im in fx_textures():
        write_texture(STAGE, f"p5joker/fx/{name}.png", im)
    # sounds: raw .ogg (p5mod/src/Vfx/Sfx.cs decodes the bytes itself, no import needed)
    (STAGE / "p5joker/sfx").mkdir(parents=True, exist_ok=True)
    for name, src in SFX.items():
        shutil.copy(src, STAGE / f"p5joker/sfx/{name}.ogg")
    files = sorted(p.relative_to(STAGE).as_posix() for p in STAGE.rglob("*") if p.is_file())
    print(len(files), "files staged in", STAGE.relative_to(ROOT))
    for f in files:
        print(" ", f)


if __name__ == "__main__":
    main()

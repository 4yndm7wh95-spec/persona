def normalise_grip(im):
    """wrist end of the opaque black hand body -> x = 360 px, its vertical centre -> y = 50 %; canvas 1800x1200 so fingertips fit"""
    W, H = 1800, 1200
    px = im.load()
    cols = {}
    ys = []
    for y in range(0, im.height, 3):
        for x in range(0, im.width, 3):
            r, g, b, a = px[x, y]
            if a > 230 and r + g + b < 60:
                cols[x] = cols.get(x, 0) + 1
                ys.append(y)
    left = min(x for x, n in cols.items() if n >= 12)
    cy = sorted(ys)[len(ys) // 2]
    out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    out.alpha_composite(im, (round(360 - left), round(H * 0.5 - cy)))
    return out.resize((W // 2, H // 2), Image.LANCZOS)


def normalise_hand(im):
    a = im.getchannel("A")
    W, H = 1024, 1536
    xs = []
    for y in range(im.height - 60, im.height - 8, 4):
        row = [x for x in range(0, im.width, 2) if a.getpixel((x, y)) > 128]
        if row:
            xs.append((row[0], row[-1]))
    l = sum(x[0] for x in xs) / len(xs)
    r = sum(x[1] for x in xs) / len(xs)
    k = 0.22 * W / max(1.0, r - l)
    bottom = a.getbbox()[3]
    sc = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
    out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    out.alpha_composite(sc, (round(W / 2 - (l + r) / 2 * k), round(H - bottom * k) + 6))
    return out.crop((0, 660, W, H)).resize((W // 2, (H - 660) // 2), Image.LANCZOS)



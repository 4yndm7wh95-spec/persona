REF = np.array(bottom + curl + top, float); TIP = np.array([423.0, 378.0]); X0 = 1340.0
W = np.ones(len(REF)); W[len(bottom):len(bottom) + len(curl)] = 1.5
def build(p):
    y0, th0, L, ka0, ka1, kp, sp, wr, kt, wf = p
    return integrate(X0, y0, th0, L, unimodal2(ka0, ka1, kp, sp, wr, kt, wf))
def res(p):
    s, x, y, th, k = build(p); d, _ = nearest(REF, x, y)
    return np.concatenate([d * W, [(x[-1] - TIP[0]) * 4, (y[-1] - TIP[1]) * 4]])
D = np.radians
p0 = [480, D(158), 1450, D(0.015), D(0.06), D(0.95), 1240, 80, D(0.12), 40]
lo = [430, D(145), 1200, 0, 0, D(0.3), 1000, 25, 0, 30]
hi = [540, D(175), 1800, D(0.08), D(0.2), D(2.0), 1400, 400, D(0.5), 400]
r = least_squares(res, p0, bounds=(lo, hi), x_scale='jac', max_nfev=3000)
p = r.x; s, x, y, th, k = build(p); d, _ = nearest(REF, x, y)
print('rms %.2f  max %.2f (at %s)  tip (%.1f,%.1f)' % (np.sqrt((d ** 2).mean()), d.max(), REF[d.argmax()], x[-1], y[-1]))
for nm, v in zip('y0 th0 L ka0 ka1 kp sp wr kt wf'.split(), p): print(' ', nm, round(float(np.degrees(v)) if nm in ('th0', 'ka0', 'ka1', 'kp', 'kt') else float(v), 4))
json.dump({'X0': X0, 'p': [float(v) for v in p]}, open('inner_fit.json', 'w'))

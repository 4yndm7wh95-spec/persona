bottom = [(1261,518),(1233,523.5),(1207,530.5),(1180,537),(1148,542),(1109,550),(1062,562),(1037,566),(1011,570.5),(986,572.5),(961,574.5),(934,578),(899,582),(871,585),(841,588.5),(814,592),(789,594),(763,596),(738,598.5),(713,598.5),(688,598.5),(663,598.5),(638,596),(612,593),(585,590.5),(559,589),(534,586.5),(509,582),(481,576.5),(455,572),(430,566),(405,558)]
curl = [(328.5,534),(315.5,528),(303,522),(293,516),(282,510),(270.5,504),(261.5,498),(252,492),(245.5,486),(238.5,480),(231.5,474),(226.5,468),(222.5,462),(218.5,456),(214.5,450),(211,444),(209.5,438),(208.5,432),(208,426),(208.5,420),(209.5,414),(211,408),(213.5,402),(217.5,396),(223.5,390),(233,384),(243,378)]
